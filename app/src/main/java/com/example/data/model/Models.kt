package com.example.data.model

import com.google.firebase.Timestamp
import com.google.firebase.firestore.DocumentId
import com.google.firebase.firestore.IgnoreExtraProperties
import com.google.firebase.firestore.ServerTimestamp

@IgnoreExtraProperties
data class Product(
    @DocumentId val id: String = "",
    val userId: String = "",
    val name: String = "",
    val code: String = "",
    val category: String = "Abarrotes",
    val unit: String = "pza",
    val supplier: String = "",
    val quantity: Long = 0L,
    val minStock: Long = 5L,
    @ServerTimestamp val createdAt: Timestamp? = null,
    @ServerTimestamp val updatedAt: Timestamp? = null
) {
    val isOutOfStock: Boolean
        get() = quantity <= 0L

    val isLowStock: Boolean
        get() = quantity <= minStock

    val stockRatio: Float
        get() {
            if (minStock <= 0L) return if (quantity > 0L) 1f else 0f
            val target = (minStock * 2L).coerceAtLeast(1L)
            return (quantity.toFloat() / target.toFloat()).coerceIn(0f, 1f)
        }
}

@IgnoreExtraProperties
data class StockEntry(
    @DocumentId val id: String = "",
    val userId: String = "",
    val productId: String = "",
    val productName: String = "",
    val productCode: String = "",
    val addedQuantity: Long = 0L,
    val previousQuantity: Long = 0L,
    val newQuantity: Long = 0L,
    val supplier: String = "",
    val notes: String = "",
    @ServerTimestamp val createdAt: Timestamp? = null
)

@IgnoreExtraProperties
data class TaskItem(
    @DocumentId val id: String = "",
    val userId: String = "",
    val title: String = "",
    val description: String = "",
    val category: String = "Reabastecimiento",
    val priority: String = "ALTA",
    val completed: Boolean = false,
    val dueDateMillis: Long = 0L,
    val reminderEnabled: Boolean = true,
    val linkedProductId: String = "",
    val linkedProductName: String = "",
    val autoGenerated: Boolean = false,
    @ServerTimestamp val createdAt: Timestamp? = null,
    @ServerTimestamp val updatedAt: Timestamp? = null
) {
    val isOverdue: Boolean
        get() = !completed && dueDateMillis > 0L && dueDateMillis < System.currentTimeMillis()
}

