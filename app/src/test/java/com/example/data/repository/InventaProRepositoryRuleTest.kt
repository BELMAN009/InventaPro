package com.example.data.repository

import com.example.base.FirestoreEmulatorTestBase
import com.google.firebase.firestore.FirebaseFirestoreException
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withTimeout
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

class InventaProRepositoryRuleTest : FirestoreEmulatorTestBase() {

    @Test
    fun createAndObserveProduct_authenticatedOwner_succeeds() = runBlocking {
        val uid = signInTestUser(ALICE_EMAIL)
        val repository = InventaProRepository(firestore, auth)

        val createResult = withTimeout(DEFAULT_TIMEOUT_MS) {
            repository.createProduct(
                name = "Leche Entera 1L",
                code = "LAC-010",
                category = "Lácteos",
                unit = "litro",
                supplier = "Lácteos del Valle",
                quantity = 6L,
                minStock = 12L
            )
        }
        assertTrue(createResult.isSuccess)
        val productId = createResult.getOrThrow()
        assertTrue(productId.isNotEmpty())

        val emittedProducts = withTimeout(FLOW_TIMEOUT_MS) {
            repository.observeProducts(uid).first { list -> list.any { it.id == productId } }
        }
        val createdProduct = emittedProducts.first { it.id == productId }
        assertEquals("Leche Entera 1L", createdProduct.name)
        assertTrue(createdProduct.isLowStock)

        // Register stock entry and verify updated quantity
        val entryResult = withTimeout(DEFAULT_TIMEOUT_MS) {
            repository.registerStockEntry(
                product = createdProduct,
                addedQuantity = 10L,
                supplier = "Lácteos del Valle",
                notes = "Surtimiento matutino"
            )
        }
        assertTrue(entryResult.isSuccess)

        val updatedProduct = withTimeout(DEFAULT_TIMEOUT_MS) {
            repository.getProductById(productId).getOrThrow()
        }
        assertEquals(16L, updatedProduct.quantity)
    }

    @Test
    fun createAndObserveTasks_authenticatedOwner_succeeds() = runBlocking {
        val uid = signInTestUser(ALICE_EMAIL)
        val repository = InventaProRepository(firestore, auth)

        val createResult = withTimeout(DEFAULT_TIMEOUT_MS) {
            repository.createTask(
                title = "Reabastecer Leche Entera 1L",
                description = "Existencias por debajo del mínimo de 12 unidades",
                category = "Reabastecimiento",
                priority = "ALTA",
                dueDateMillis = System.currentTimeMillis() + 7200_000L,
                reminderEnabled = true,
                linkedProductId = "prod_test_1",
                linkedProductName = "Leche Entera 1L",
                autoGenerated = true
            )
        }
        assertTrue(createResult.isSuccess)
        val taskId = createResult.getOrThrow()

        val emittedTasks = withTimeout(FLOW_TIMEOUT_MS) {
            repository.observeTasks(uid).first { list -> list.any { it.id == taskId } }
        }
        assertTrue(emittedTasks.any { it.id == taskId && it.autoGenerated })
    }

    @Test
    fun getTaskById_crossUserAccess_failsWithPermissionDenied() = runBlocking {
        signInTestUser(ALICE_EMAIL)
        val aliceRepo = InventaProRepository(firestore, auth)
        val taskId = withTimeout(DEFAULT_TIMEOUT_MS) {
            aliceRepo.createTask(
                title = "Revisar anaquel de papelería",
                description = "Conteo físico semanal",
                category = "Inventario",
                priority = "MEDIA"
            ).getOrThrow()
        }

        signInTestUser(BOB_EMAIL)
        val bobRepo = InventaProRepository(firestore, auth)
        val result = withTimeout(DEFAULT_TIMEOUT_MS) {
            bobRepo.getTaskById(taskId)
        }
        assertTrue(result.isFailure)
        val firestoreException = result.exceptionOrNull()?.unwrapFirestoreException()
        assertNotNull(firestoreException)
        assertEquals(FirebaseFirestoreException.Code.PERMISSION_DENIED, firestoreException?.code)
    }

    @Test
    fun observeTasks_unauthenticatedUser_failsWithPermissionDenied() = runBlocking {
        auth.signOut()
        val repository = InventaProRepository(firestore, auth)

        var caught: Throwable? = null
        try {
            withTimeout(FLOW_TIMEOUT_MS) {
                repository.observeTasks("unauth_uid").first()
            }
        } catch (e: Throwable) {
            caught = e
        }
        assertNotNull(caught)
        val firestoreException = caught?.unwrapFirestoreException()
        assertNotNull(firestoreException)
        assertEquals(FirebaseFirestoreException.Code.PERMISSION_DENIED, firestoreException?.code)
    }

    private companion object {
        const val ALICE_EMAIL = "alice@inventapro.test"
        const val BOB_EMAIL = "bob@inventapro.test"
        const val DEFAULT_TIMEOUT_MS = 5000L
        const val FLOW_TIMEOUT_MS = 3000L
    }
}
