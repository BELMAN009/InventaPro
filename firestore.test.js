const {
  initializeTestEnvironment,
  assertFails,
  assertSucceeds,
} = require("@firebase/rules-unit-testing");
const { test, before, after, beforeEach } = require("node:test");
const fs = require("node:fs");

let testEnv;
const PROJECT_ID = process.env.GCP_PROJECT || "demo-no-project";
const ALICE_UID = "alice_123";
const BOB_UID = "bob_456";

const [emulatorHost, emulatorPortStr] = (
  process.env.FIRESTORE_EMULATOR_HOST || "127.0.0.1:8085"
).split(":");
const emulatorPort = parseInt(emulatorPortStr, 10);

before(async () => {
  const rules = fs.readFileSync("./firestore.rules", "utf8");
  testEnv = await initializeTestEnvironment({
    projectId: PROJECT_ID,
    firestore: {
      rules,
      host: emulatorHost,
      port: emulatorPort,
    },
  });
});

after(async () => {
  if (testEnv) {
    await testEnv.cleanup();
  }
});

beforeEach(async () => {
  if (testEnv) {
    await testEnv.clearFirestore();
  }
});

test("Unauthenticated user: cannot read products, stock_entries, or tasks", async () => {
  const unauthDb = testEnv.unauthenticatedContext().firestore();
  await assertFails(unauthDb.collection("products").get());
  await assertFails(unauthDb.collection("stock_entries").get());
  await assertFails(unauthDb.collection("tasks").get());
});

test("Authenticated user: can create and query own product, cannot read other user's product", async () => {
  const now = new Date();
  await testEnv.withSecurityRulesDisabled(async (context) => {
    await context.firestore().collection("products").doc("bob_prod_1").set({
      userId: BOB_UID,
      name: "Aceite Vegetal 1L",
      code: "AB-001",
      category: "Abarrotes",
      unit: "pza",
      supplier: "Distribuidora Central",
      quantity: 4,
      minStock: 10,
      createdAt: now,
      updatedAt: now,
    });
  });

  const aliceDb = testEnv.authenticatedContext(ALICE_UID).firestore();
  await assertFails(aliceDb.collection("products").doc("bob_prod_1").get());

  await assertSucceeds(
    aliceDb.collection("products").doc("alice_prod_1").set({
      userId: ALICE_UID,
      name: "Cuaderno Profesional 100 Hojas",
      code: "PAP-101",
      category: "Papelería",
      unit: "pza",
      supplier: "Papelera Nacional",
      quantity: 8,
      minStock: 15,
      createdAt: now,
      updatedAt: now,
    })
  );

  await assertSucceeds(
    aliceDb.collection("products").where("userId", "==", ALICE_UID).get()
  );
  await assertFails(aliceDb.collection("products").get());
});

test("Authenticated user: rejects shadow field injection on product create", async () => {
  const now = new Date();
  const aliceDb = testEnv.authenticatedContext(ALICE_UID).firestore();
  await assertFails(
    aliceDb.collection("products").doc("alice_prod_bad").set({
      userId: ALICE_UID,
      name: "Arroz 1kg",
      code: "AB-002",
      category: "Abarrotes",
      unit: "kg",
      supplier: "Granos MX",
      quantity: 12,
      minStock: 5,
      isAdmin: true,
      createdAt: now,
      updatedAt: now,
    })
  );
});

test("Authenticated user: can create and update own task, rejects cross-user task access", async () => {
  const now = new Date();
  const aliceDb = testEnv.authenticatedContext(ALICE_UID).firestore();
  await assertSucceeds(
    aliceDb.collection("tasks").doc("task_1").set({
      userId: ALICE_UID,
      title: "Reabastecer Cuaderno Profesional",
      description: "Solicitar 30 unidades al proveedor antes del viernes.",
      category: "Reabastecimiento",
      priority: "ALTA",
      completed: false,
      dueDateMillis: Date.now() + 86400000,
      reminderEnabled: true,
      linkedProductId: "alice_prod_1",
      linkedProductName: "Cuaderno Profesional 100 Hojas",
      autoGenerated: true,
      createdAt: now,
      updatedAt: now,
    })
  );

  await assertSucceeds(
    aliceDb.collection("tasks").doc("task_1").update({
      completed: true,
      updatedAt: new Date(),
    })
  );

  const bobDb = testEnv.authenticatedContext(BOB_UID).firestore();
  await assertFails(bobDb.collection("tasks").doc("task_1").get());
  await assertFails(
    bobDb.collection("tasks").doc("task_1").update({ completed: false })
  );
});

test("Authenticated user: can create valid stock entry and rejects tampered math", async () => {
  const now = new Date();
  const aliceDb = testEnv.authenticatedContext(ALICE_UID).firestore();
  await assertSucceeds(
    aliceDb.collection("stock_entries").doc("entry_1").set({
      userId: ALICE_UID,
      productId: "alice_prod_1",
      productName: "Cuaderno Profesional 100 Hojas",
      productCode: "PAP-101",
      addedQuantity: 20,
      previousQuantity: 8,
      newQuantity: 28,
      supplier: "Papelera Nacional",
      notes: "Entrega de pedido quincenal",
      createdAt: now,
    })
  );

  // Tampered newQuantity != previousQuantity + addedQuantity must fail
  await assertFails(
    aliceDb.collection("stock_entries").doc("entry_bad").set({
      userId: ALICE_UID,
      productId: "alice_prod_1",
      productName: "Cuaderno Profesional 100 Hojas",
      productCode: "PAP-101",
      addedQuantity: 20,
      previousQuantity: 8,
      newQuantity: 999,
      supplier: "Papelera Nacional",
      notes: "Manipulación de stock",
      createdAt: now,
    })
  );
});
